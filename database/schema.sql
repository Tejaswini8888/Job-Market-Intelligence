    'Clean, canonical skill name, e.g. "Python". Uniqueness is case-insensitive via uq_skills_skill_name_lower.';
COMMENT ON COLUMN skills.skill_category IS
    'Analytical grouping used for aggregation, e.g. Programming Language, Database, Cloud, Data Science, Soft Skill.';

COMMENT ON TABLE  job_skills IS
    'Junction table resolving the MANY-TO-MANY relationship between jobs and skills. One row = this job requires this skill.';

COMMENT ON COLUMN job_skills.job_id IS
    'FK -> jobs.job_id. Part of the composite primary key. ON DELETE CASCADE.';
COMMENT ON COLUMN job_skills.skill_id IS
    'FK -> skills.skill_id. Part of the composite primary key. ON DELETE RESTRICT: a skill still in use cannot be deleted.';


-- =============================================================================
-- SUMMARY
--   companies  1 --- N  jobs
--   skills     N --- M  jobs      (through job_skills)
-- =============================================================================

COMMIT;
