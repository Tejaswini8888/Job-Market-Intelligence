COMMENT ON COLUMN companies.company_size IS
    'Normalised headcount bucket: MICRO_1_10, SMALL_11_50, MEDIUM_51_200, LARGE_201_500, XLARGE_501_1000, ENTERPRISE_1000_PLUS, UNKNOWN. NULL = not disclosed.';
COMMENT ON COLUMN companies.headquarters IS
    'Free-text headquarters city/country. NULL = not available.';

