    'Title as advertised, e.g. "Data Analyst". Analysed in a normalised (lowercase, trimmed) form.';
COMMENT ON COLUMN jobs.location IS
    'City / office location as advertised. May be "Remote" for remote postings.';
COMMENT ON COLUMN jobs.country IS
    'Country of the posting. Expected format: ISO 3166-1 alpha-2 (e.g. IN, US, GB).';
COMMENT ON COLUMN jobs.employment_type IS
    'Contract type: FULL_TIME, PART_TIME, CONTRACT, INTERNSHIP, TEMPORARY, FREELANCE, OTHER, UNKNOWN.';
COMMENT ON COLUMN jobs.work_mode IS
    'Work arrangement: REMOTE, HYBRID, ONSITE, UNKNOWN. The single most requested field for job-market analytics.';
